#!/bin/bash

# ============================================================================
# GastroLog Admin - Script para iniciar o Admin Dashboard
# ============================================================================

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR"

echo "??????????????????????????????????????????????????????????????"
echo "?     ?? GastroLog Admin Dashboard                           ?"
echo "??????????????????????????????????????????????????????????????"
echo ""

# Verificar se as dependências estão instaladas
echo "?? Verificando dependências..."

if ! command -v node &> /dev/null; then
    echo "? Node.js não está instalado!"
    exit 1
fi

if ! command -v npm &> /dev/null; then
    echo "? npm não está instalado!"
    exit 1
fi

# Verificar se node_modules existe
if [ ! -d "node_modules" ]; then
    echo "??  Instalando dependências..."
    npm install
fi

# Verificar se .env existe
if [ ! -f ".env" ]; then
    echo "??  Arquivo .env não encontrado!"
    echo "   Copiando .env.example para .env"
    cp .env.example .env
    echo "   ??  Lembre-se de configurar as variáveis de ambiente!"
fi

# Verificar conexão com banco de dados
echo "?? Verificando conexão com PostgreSQL..."

if ! npm run migrate:status &> /dev/null; then
    echo "??  Banco de dados não está sincronizado!"
    echo "   Execute: npm run migrate:dev"
fi

# Iniciar admin server
echo ""
echo "? Iniciando Admin Dashboard..."
echo ""
echo "??????????????????????????????????????????????????????????????"
echo "?                                                            ?"
echo "?  ?? Acesso: http://localhost:3002/admin                   ?"
echo "?                                                            ?"
echo "?  ?? Dicas:                                                ?"
echo "?     ? Visualize tabelas em tempo real                     ?"
echo "?     ? Consulte dados com paginação                        ?"
echo "?     ? Veja a estrutura do banco                           ?"
echo "?     ? Execute queries customizadas                        ?"
echo "?                                                            ?"
echo "?  ?? Para parar: Pressione Ctrl+C                          ?"
echo "?                                                            ?"
echo "??????????????????????????????????????????????????????????????"
echo ""

# Iniciar o servidor
node admin-server.js
