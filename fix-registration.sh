#!/bin/bash

echo "?? Diagnosticando Problema de Registro - GastroLog"
echo "=================================================="
echo ""

# Cores
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m'

echo -e "${BLUE}1. Verificando Prisma...${NC}"
npm run prisma:generate 2>&1 | tail -5
echo ""

echo -e "${BLUE}2. Verificando conexão com banco de dados...${NC}"
echo "DATABASE_URL: $(grep DATABASE_URL .env | cut -d'=' -f2)"
echo ""

echo -e "${BLUE}3. PROBLEMA IDENTIFICADO:${NC}"
echo -e "${RED}? Usuário do PostgreSQL não tem permissão para criar database${NC}"
echo ""

echo -e "${YELLOW}SOLUÇÃO:${NC}"
echo ""
echo "Opção 1: Dar permissão ao usuário (recomendado)"
echo "?????????????????????????????????????????????????"
echo "sudo su - postgres"
echo "ALTER USER gastrouser CREATEDB;"
echo "\q"
echo ""

echo "Opção 2: Usar usuário postgres (alternativa)"
echo "??????????????????????????????????????????????"
echo "Editar .env e mudar:"
echo "DATABASE_URL=postgresql://postgres:senha@localhost:5432/gastroapp_db"
echo ""

echo "Opção 3: Usar push em vez de migrate (mais rápido)"
echo "???????????????????????????????????????????????????"
echo "Adicionar script ao package.json:"
echo '"prisma:db:push": "prisma db push --skip-generate"'
echo ""

echo "PRÓXIMO PASSO:"
echo "?????????????????????????????????????????????????"
echo ""
echo "Depois de resolver o problema acima, execute:"
echo ""
echo -e "${GREEN}npm run prisma:migrate${NC}"
echo ""
echo "Ou (mais rápido):"
echo -e "${GREEN}npx prisma db push${NC}"
echo ""
